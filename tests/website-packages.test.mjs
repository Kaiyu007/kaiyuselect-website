import test from 'node:test';
import assert from 'node:assert/strict';
import { websitePackages, packageSubject } from '../src/data/website-packages.js';
import { enquiryPrefill, validateEnquiry, emailLink, clipboardText } from '../src/lib/enquiry.js';
import { onRequest } from '../functions/api/enquiry.js';

const choices = websitePackages.flatMap(pkg => (pkg.business ? ['', 'Booking', 'Online Store'] : ['']).map(option => ({ subject: packageSubject(pkg, option) })));
const fields = { name: 'Synthetic Package Review', email: 'review@example.com', type: 'webdesign', message: 'Synthetic package enquiry. Local validation only; no real delivery.' };

test('approved package prices, enquiry forms and independent entry allowances remain intact', () => {
  assert.deepEqual(websitePackages.map(pkg => pkg.price), ['A$298', 'A$458', 'A$798', 'A$1,078', 'A$1,560']);
  assert.deepEqual(websitePackages.slice(0, 2).map(pkg => pkg.scope), [
    ['One-page presentation website', 'No content management backend'],
    ['Up to five standard pages', 'No content management backend'],
  ]);
  assert.equal(packageSubject(websitePackages[1]), 'Website package enquiry — A$458 Essential Business Website');
  for (const pkg of websitePackages.slice(2)) {
    assert.ok(pkg.scope.includes('Standard enquiry form'));
    assert.ok(pkg.highlights.includes('Standard enquiry form'));
  }
  assert.ok(websitePackages[2].scope.includes('Up to 10 initial case-study OR article entries; choose one content type'));
  assert.ok(websitePackages[3].scope.includes('Up to 15 initial case-study and article entries combined'));
  assert.ok(websitePackages[4].scope.includes('Up to 20 initial case-study and article entries combined'));
  for (const pkg of websitePackages.slice(3)) {
    assert.ok(pkg.scope.some(item => item.includes('Booking OR Small Online Store')));
  }
});

test('all nine package choices survive native GET encoding, Contact prefill, validation and both fallbacks', () => {
  assert.equal(choices.length, 9);
  for (const { subject } of choices) {
    const query = new URLSearchParams({ type: 'webdesign', subject });
    const prefill = enquiryPrefill('?' + query);
    assert.deepEqual(prefill, { type: 'webdesign', subject });
    const data = { ...fields, ...prefill };
    assert.equal(validateEnquiry(data).valid, true, subject);
    assert.equal(new URL(emailLink(data)).searchParams.get('subject'), subject);
    assert.ok(clipboardText(data).includes(`Subject: ${subject}`));
  }
});

test('the existing Function accepts package subjects and preserves price / selected function using mocked providers only', async t => {
  let sent;
  let providerCalls = 0;
  t.mock.method(globalThis, 'fetch', async (url, options) => {
    if (url === 'https://challenges.cloudflare.com/turnstile/v0/siteverify') return Response.json({ success: true, hostname: 'kaiyuselect.com.au', action: 'enquiry' });
    assert.equal(url, 'https://api.resend.com/emails');
    sent = JSON.parse(options.body); providerCalls++;
    return Response.json({ id: 'local-mock-only' });
  });
  for (const [index, { subject }] of choices.entries()) {
    const request = new Request('https://kaiyuselect.com.au/api/enquiry/', {
      method: 'POST', headers: { Origin: 'https://kaiyuselect.com.au', 'Content-Type': 'application/json', 'CF-Connecting-IP': '192.0.2.1' },
      body: JSON.stringify({ ...fields, subject, website: '', token: 'mock-proof', requestId: `aaaaaaaa-aaaa-4aaa-aaaa-${String(index).padStart(12, '0')}` }),
    });
    const response = await onRequest({ request, env: { CONTACT_ONLINE_ENABLED: 'true', RESEND_API_KEY: 'test-only', TURNSTILE_SECRET_KEY: 'test-only', CONTACT_FROM_EMAIL: 'review@example.com', ENQUIRY_LIMITS: { get: async () => null, put: async () => {} } } });
    assert.equal(response.status, 200);
    assert.equal(sent.subject, '[Website Design Enquiries] ' + subject);
    assert.deepEqual(sent.to, ['contact@kaiyuselect.com.au']);
    assert.equal(sent.reply_to, fields.email);
    assert.equal(sent.html, undefined);
  }
  assert.equal(providerCalls, 9);
});
